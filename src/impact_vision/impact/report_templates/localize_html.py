_TEXT = re.compile(r">([^<>]+)<")
_SKIP = re.compile(r"<(style|script)\b[^>]*>.*?</\1>", re.DOTALL | re.IGNORECASE)
_TITLE = re.compile(r"(<title>)([^<]*)(</title>)")
LANGS = ("zh-HK", "zh-CN")


@lru_cache(maxsize=1)
def _derived() -> dict[str, Any]:
    """zh-CN tables built by ``scripts/build_phrasebook.py`` (``labels`` / ``label_patterns``)."""
    import yaml

    from impact_vision.impact._paths import data_path

    path = data_path("i18n/phrasebook.yaml")
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else {}
    doc = doc or {}
    return {"labels": doc.get("labels") or {}, "label_patterns": doc.get("label_patterns") or {}}


@lru_cache(maxsize=2)
def _labels(lang: str) -> dict[str, str]:
    authored = {**_EXTRA, **LABELS_ZH_HK}
    if lang == "zh-HK":
        return authored
    cn = _derived()["labels"]
    return {en: str(cn[en]) for en in authored if en in cn}


@lru_cache(maxsize=2)
def _patterns(lang: str) -> list[tuple[re.Pattern[str], str]]:
    if lang == "zh-HK":
        return _PATTERNS
    cn = _derived()["label_patterns"]
    return [(rx, str(cn[rx.pattern])) for rx, _ in _PATTERNS if rx.pattern in cn]


@lru_cache(maxsize=2)
def _strings_index(lang: str) -> tuple[dict[str, str], list[tuple[re.Pattern[str], str]]]:
    """The report string table (``design/strings.py``) read backwards: English text -> ``lang``.

    Plain entries match exactly; entries with ``{slots}`` become patterns whose
    slots are carried over. SDG goal names map to the official Chinese names.
    """
    from impact_vision.impact.report_templates.design.strings import EN, SDG_NAMES, SECTOR_NAMES, STRINGS
    from impact_vision.impact.sdg_taxonomy import get_sdg_goals

    zh = STRINGS[lang]
    exact: dict[str, str] = {}
    pats: list[tuple[re.Pattern[str], str]] = []
    for key, en in EN.items():
        target = zh.get(key)
        if not target or target == en or not en.strip():
            continue
        if key.startswith("gwc_"):  # the classification itself is the key ("Substantive with Gaps")
            exact.setdefault(key[4:], target)
        if "{" not in en:
            exact.setdefault(en.strip(), target)
            continue
        parts = re.split(r"\{(\w+)\}", en)
        names = parts[1::2]
        if len(set(names)) != len(names) or not re.sub(r"\{\w+\}", "", en).strip():
            continue
        rx = "".join(re.escape(p) if i % 2 == 0 else f"(?P<{p}>.+?)" for i, p in enumerate(parts))
        pats.append((re.compile(f"^{rx}$"), target))
    pats.sort(key=lambda p: -len(re.sub(r"\(\?P<\w+>\.\+\?\)", "", p[0].pattern)))  # most literal text first
    for slug, name in SECTOR_NAMES.get(lang, {}).items():
        exact.setdefault(slug, name)
        exact.setdefault(slug.replace("_", " ").title(), name)
    for goal in get_sdg_goals():
        name = SDG_NAMES.get(lang, {}).get(goal.number)
        if name:
            exact.setdefault(goal.name, name)
    return exact, pats


def _lookup(core: str, lang: str) -> str | None:
    hit = _labels(lang).get(core) or _dd_questions(lang).get(core)
    if hit is not None:
        return hit
    exact, pats = _strings_index(lang)
    if core in exact:
        return exact[core]
    if _SCORE_NOTE.match(core):
        out = core
        for en, zh in _SCORE_WORDS[lang].items():
            out = out.replace(f"{en}=", f"{zh}=")
        return out.replace(", ", "，")
    for rx, tmpl in _patterns(lang):
        m = rx.match(core)
        if m:
            parts = {k: (localize_text(v, lang) if k in _RECURSE else v) for k, v in m.groupdict().items()}
            return tmpl.format(**parts)
    for rx, tmpl in pats:
        m = rx.match(core)
        if m:
            try:
                return tmpl.format(**{k: localize_text(v, lang) for k, v in m.groupdict().items()})
            except (KeyError, IndexError):  # a slot the English template lacks
                continue
    out = localize(core, lang)
    return out if out != core else None


def localize_text(text: str, lang: str = "zh-HK") -> str:
    """Translate one label or generated sentence; unknown text is unchanged.

    A run of several sentences is translated sentence by sentence, but only
    when *every* sentence is known: a company's own text is never half-translated.
    """
    if lang not in LANGS or not text.strip():
        return text
    core = text.strip()
    hit = _lookup(core, lang)
    if hit is None:
        pieces = _SENTENCE.split(core)
        if len(pieces) > 1:
            done = [_lookup(p, lang) for p in pieces]
            if all(d is not None for d in done):
                hit = "".join(str(d) for d in done)
    if hit is None:
        return text
    lead = text[: len(text) - len(text.lstrip())]
    trail = text[len(text.rstrip()):]
    return f"{lead}{hit}{trail}"


def _node(m: re.Match[str], lang: str) -> str:
    raw = m.group(1)
    plain = _html.unescape(raw)
    out = localize_text(plain, lang)
    if out == plain:
        return m.group(0)
    return f">{_html.escape(out, quote=False)}<"


def localize_document(document: str, lang: str = "en") -> str:
    """Return ``document`` with labels and generated sentences in ``lang``."""
    if lang not in LANGS:
        return document
    pieces: list[str] = []
    pos = 0
    for block in _SKIP.finditer(document):
        pieces.append(_TEXT.sub(lambda m: _node(m, lang), document[pos:block.start()]))
        pieces.append(block.group(0))
        pos = block.end()
    pieces.append(_TEXT.sub(lambda m: _node(m, lang), document[pos:]))
    out = "".join(pieces)
    out = out.replace('<html lang="en"', f'<html lang="{lang}"', 1)
    return _TITLE.sub(
        lambda m: m.group(1) + _html.escape(localize_text(_html.unescape(m.group(2)), lang), quote=False) + m.group(3),
        out, count=1,
    )


