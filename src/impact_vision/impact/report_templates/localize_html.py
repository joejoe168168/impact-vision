_RECURSE = {"a"}
_EXTRA = {"INSUFFICIENT EVIDENCE": "證據不足", "insufficient evidence": "證據不足"}

_TEXT = re.compile(r">([^<>]+)<")
_SKIP = re.compile(r"<(style|script)\b[^>]*>.*?</\1>", re.S | re.I)
_TITLE = re.compile(r"(<title>)([^<]*)(</title>)")


def localize_text(text: str, lang: str = "zh-HK") -> str:
    """Translate one label or generated sentence; unknown text is unchanged."""
    if lang != "zh-HK" or not text.strip():
        return text
    core = text.strip()
    hit = LABELS_ZH_HK.get(core) or _EXTRA.get(core) or _dd_questions().get(core)
    if hit is None:
        for rx, tmpl in _PATTERNS:
            m = rx.match(core)
            if m:
                parts = {k: (localize_text(v, lang) if k in _RECURSE else v) for k, v in m.groupdict().items()}
                hit = tmpl.format(**parts)
                break
    if hit is None:
        out = localize(core, lang)
        hit = out if out != core else None
    if hit is None:
        return text
    lead = text[: len(text) - len(text.lstrip())]
    trail = text[len(text.rstrip()):]
    return f"{lead}{hit}{trail}"


def _node(m: re.Match[str], lang: str) -> str:
    raw = m.group(1)
    plain = _html.unescape(raw)
    out = localize_text(plain, lang)
    if out == plain:
        return m.group(0)
    return f">{_html.escape(out, quote=False)}<"


def localize_document(document: str, lang: str = "en") -> str:
    """Return ``document`` with labels and generated sentences in ``lang``."""
    if lang != "zh-HK":
        return document
    pieces: list[str] = []
    pos = 0
    for block in _SKIP.finditer(document):
        pieces.append(_TEXT.sub(lambda m: _node(m, lang), document[pos:block.start()]))
        pieces.append(block.group(0))
        pos = block.end()
    pieces.append(_TEXT.sub(lambda m: _node(m, lang), document[pos:]))
    out = "".join(pieces)
    out = out.replace('<html lang="en"', '<html lang="zh-HK"', 1)
    return _TITLE.sub(
        lambda m: m.group(1) + _html.escape(localize_text(_html.unescape(m.group(2)), lang), quote=False) + m.group(3),
        out, count=1,
    )


