@lru_cache(maxsize=2)
def _dd_questions(lang: str = "zh-HK") -> dict[str, str]:
    """English DD question (and follow-up) text -> ``lang`` text, matched by question id."""
    from impact_vision.impact.dd_checklist import load_checklist
    from impact_vision.impact.i18n import load_dd_checklist_localized

    rows = {q["id"]: q for q in (load_dd_checklist_localized(lang).get("questions") or [])}
    out: dict[str, str] = {}
    try:
        for q in load_checklist():
            row = rows.get(q.id)
            if not row:
                continue
            out[q.question.strip()] = row["question"]
            if getattr(q, "follow_up", None) and row.get("follow_up"):
                out[str(q.follow_up).strip()] = row["follow_up"]
    except Exception:  # noqa: BLE001 - a missing checklist must not break a report
        return {}
    return out


